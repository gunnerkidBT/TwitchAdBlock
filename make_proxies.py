#!/usr/bin/env python3
"""Build the default server list: proxies.json (downloaded by the app at
launch) and Secrets.h (the list built into the app, plus the decryption key).

Lets you add, remove or swap servers without releasing an update: commit and
push proxies.json and apps pick it up the next time they open. Rebuild the app
with the new Secrets.h at release time so fresh installs get it too.

Servers come from proxies.local.txt (never committed), one per line:

    Portugal | user:pass@1.2.3.4:8000
    Serbia   | user:pass@5.6.7.8:8000
    Russia   | user:pass@9.10.11.12:8000 | backup

"backup" servers are only used on Automatic when every other one is down.
Lines starting with # are ignored.

Addresses are encrypted (AES-256-CBC + HMAC-SHA256). The key lives in
proxies.key (never committed; created on first run). Keep it: released apps
can only read lists made with the same key. Secrets.h is never committed
either. Without it the app builds with no built-in servers (Custom Proxy only).

Usage:
    python make_proxies.py            # write proxies.json + Secrets.h from proxies.local.txt
    python make_proxies.py --builtin  # proxies.json tells apps to use their built-in list
    python make_proxies.py --show     # print what proxies.json contains

Needs: pip install cryptography
"""
import base64
import hashlib
import hmac
import json
import os
import re
import sys
from pathlib import Path

try:
    from cryptography.hazmat.primitives import padding
    from cryptography.hazmat.primitives.ciphers import Cipher, algorithms, modes
except ImportError:
    sys.exit("Needs the cryptography package: pip install cryptography")

HERE = Path(__file__).resolve().parent
LOCAL = HERE / "proxies.local.txt"
KEYFILE = HERE / "proxies.key"
OUT = HERE / "proxies.json"
SECRETS = HERE / "Secrets.h"

ADDR = re.compile(r"^(?:[^:@\s]+:[^@\s]*@)?[A-Za-z0-9.\-]+:\d{1,5}$")


def load_pieces():
    """Three 32-byte key pieces. The app rebuilds the keys from them at runtime."""
    if not KEYFILE.exists():
        pieces = [os.urandom(32) for _ in range(3)]
        KEYFILE.write_text("\n".join(p.hex() for p in pieces) + "\n", encoding="utf-8")
        print(f"Created {KEYFILE.name}. Keep it safe and never commit it.")
    pieces = [bytes.fromhex(l.strip()) for l in KEYFILE.read_text(encoding="utf-8").split() if l.strip()]
    if len(pieces) != 3 or any(len(p) != 32 for p in pieces):
        sys.exit(f"{KEYFILE.name} is damaged (expected 3 lines of 64 hex characters)")
    return pieces


def keys(pieces):
    a, b, c = pieces
    # Must match twab_deriveKeys in TWABRemoteProxies.m.
    enc = hashlib.sha256(b"twab-enc" + a + b).digest()
    mac = hashlib.sha256(b"twab-mac" + b + c).digest()
    return enc, mac


def encrypt(text, enc, mac):
    iv = os.urandom(16)
    padder = padding.PKCS7(128).padder()
    data = padder.update(text.encode()) + padder.finalize()
    enc_ = Cipher(algorithms.AES(enc), modes.CBC(iv)).encryptor()
    ct = enc_.update(data) + enc_.finalize()
    tag = hmac.new(mac, iv + ct, hashlib.sha256).digest()
    return base64.b64encode(iv + ct + tag).decode()


def decrypt(b64, enc, mac):
    raw = base64.b64decode(b64)
    iv, ct, tag = raw[:16], raw[16:-32], raw[-32:]
    if not hmac.compare_digest(tag, hmac.new(mac, iv + ct, hashlib.sha256).digest()):
        raise ValueError("tag mismatch (made with a different key?)")
    dec = Cipher(algorithms.AES(enc), modes.CBC(iv)).decryptor()
    data = dec.update(ct) + dec.finalize()
    unpadder = padding.PKCS7(128).unpadder()
    return (unpadder.update(data) + unpadder.finalize()).decode()


def c_bytes(name, data):
    rows = [", ".join(f"0x{b:02X}" for b in data[i:i + 8]) for i in range(0, len(data), 8)]
    return f"static const uint8_t {name}[] = {{\n    " + ",\n    ".join(rows) + ",\n};\n"


def write_secrets(pieces, list_json):
    literal = json.dumps(list_json)  # a valid C string literal for plain ASCII JSON
    SECRETS.write_text(
        "// Generated by make_proxies.py. NEVER COMMIT (it's in .gitignore).\n"
        "// Key pieces for the server list, and the list built into the app.\n"
        "#pragma once\n#include <stdint.h>\n\n"
        + c_bytes("twab_kp_a", pieces[0]) + "\n"
        + c_bytes("twab_kp_b", pieces[1]) + "\n"
        + c_bytes("twab_kp_c", pieces[2]) + "\n"
        + f"#define TWAB_BUILTIN_LIST {literal}\n",
        encoding="utf-8")


def build():
    if not LOCAL.exists():
        sys.exit(f"Missing {LOCAL.name}. Create it with one 'Name | user:pass@host:port' per line.")
    pieces = load_pieces()
    enc, mac = keys(pieces)
    proxies = []
    for n, line in enumerate(LOCAL.read_text(encoding="utf-8").splitlines(), 1):
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        parts = [p.strip() for p in line.split("|")]
        if len(parts) < 2 or not parts[0]:
            sys.exit(f"Line {n}: expected 'Name | user:pass@host:port [| backup]'")
        name, addr = parts[0], parts[1]
        if not ADDR.match(addr):
            sys.exit(f"Line {n}: '{name}' address doesn't look like user:pass@host:port")
        if not name.isascii() or '"' in name or "\\" in name:
            sys.exit(f"Line {n}: keep server names to plain letters")
        backup = len(parts) > 2 and parts[2].lower() == "backup"
        proxies.append({"name": name, "backup": backup, "addr": encrypt(addr, enc, mac)})
    if not proxies:
        sys.exit("No servers in proxies.local.txt")
    if all(p["backup"] for p in proxies):
        print("Warning: every server is marked backup, so they'll all be used normally.")
    data = {"v": 2, "proxies": proxies}
    OUT.write_text(json.dumps(data, indent=2) + "\n", encoding="utf-8")
    write_secrets(pieces, json.dumps(data, separators=(",", ":")))
    print("Servers: " + ", ".join(p["name"] + (" (backup)" if p["backup"] else "") for p in proxies))
    print(f"Wrote {OUT.name} (commit and push; apps update on next launch)")
    print(f"Wrote {SECRETS.name} (not committed; rebuild the app to update its built-in list)")


def builtin():
    OUT.write_text(json.dumps({"v": 2, "useBuiltin": True}, indent=2) + "\n", encoding="utf-8")
    print(f"Wrote {OUT.name}: apps will go back to their built-in list. Commit and push it.")


def show():
    data = json.loads(OUT.read_text(encoding="utf-8"))
    if data.get("useBuiltin"):
        print("proxies.json tells apps to use their built-in list.")
        return
    enc, mac = keys(load_pieces())
    for p in data["proxies"]:
        host = decrypt(p["addr"], enc, mac).split("@")[-1]
        print(f"{p['name']:<12} {host}{'  (backup)' if p.get('backup') else ''}")


if __name__ == "__main__":
    arg = sys.argv[1] if len(sys.argv) > 1 else ""
    {"--builtin": builtin, "--show": show}.get(arg, build)()
